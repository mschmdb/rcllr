test("months sorted descending", () => {
  const target = repo();
  target.write("topics/a/note.md", "2026-08-06 and 2026-09-06.\n");
  target.write("topics/b/note.md", "2026-08-06 and 2026-09-06 too.\n");
  const ordered = links(target, 2).time_links.map((item) => item.month);
  assert.deepEqual(ordered, [...ordered].sort((a, b) => compare(b, a)));
});

