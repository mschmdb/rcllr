function scoped(target: Brain, name: string, scope: string, text = "In August 2026 there is a deadline.\n"): void {
  target.write("topics/" + name + "/README.md", "---\nscope: " + scope + "\n---\n\n# " + name + "\n");
  target.write("topics/" + name + "/note.md", text);
}

test("collision between barrier scopes", () => {
  const target = repo();
  scoped(target, "job", "work");
  scoped(target, "holiday", "private");
  const entry = links(target).collisions.find((item) => item.month === "2026-08")!;
  assert.deepEqual([...entry.scopes], [["work", ["job"]], ["private", ["holiday"]]]);
});

test("collision: one line per month, at most eight", () => {
  const target = repo();
  for (let index = 0; index < 9; index++) scoped(target, "job" + index, "work");
  scoped(target, "holiday", "private");
  const entries = links(target).collisions.filter((item) => item.month === "2026-08");
  assert.equal(entries.length, 1);
  assert.equal(entries[0]!.scopes.get("work")!.length, 8);
  assert.deepEqual(entries[0]!.scopes.get("private"), ["holiday"]);
});

test("collision needs both scopes and ignores flat notes", () => {
  const target = repo();
  scoped(target, "job1", "work");
  scoped(target, "job2", "work");
  target.write("notes/whatever.md", "In August 2026 something happens.\n");
  assert.deepEqual(links(target).collisions, []);
});

test("collision Markdown in German", () => {
  const target = hub();
  scoped(target, "arbeit", "work", "Im August 2026 ist Deadline.\n");
  scoped(target, "urlaub", "privat", "Im August 2026 ist Urlaub.\n");
  target.commit();
  const content = fs.readFileSync(writeLinks(target.config), "utf-8");
  assert.ok(content.includes("work: arbeit × privat: urlaub"));
});

test("a sensitive topic is excluded and counted", () => {
  const target = repo();
  target.write("topics/hidden/README.md", "> SENSITIVE\n\n# Hidden\n");
  target.write("topics/hidden/note.md", "Acme in August 2026.\n");
  target.write("topics/open/note.md", "Acme in August 2026.\n");
  target.write("entities.txt", "Acme\n");
  const data = links(target, 1);
  for (const item of [...data.entity_links, ...data.time_links]) assert.ok(!item.topics.includes("topics/hidden"));
  assert.ok(data.sensitive_files >= 1 && data.sensitive_topics >= 1);
});

test("CLI JSON and a disabled extra", () => {
  const target = repo();
  target.write("topics/a/note.md", "x\n");
  target.commit();
  const result = invoke(target, ["links", "--json"]);
  assert.equal(result.code, 0);
  assert.deepEqual(JSON.parse(result.out).time_links, []);
  target.configure("[extras]\nlinks = false\n");
  const disabled = invoke(target, ["links", "--serious"]);
  assert.ok(disabled.code === 2 && disabled.err.includes("extras"));
});

