/** Status lines that report success; their cheeky version may replace the plain text. */
export const INFO_KEYS: ReadonlySet<string> = new Set(["sync_ok"]);

export const TONES = ["cheeky", "plain"] as const;

export function text(key: string, tone: string, params: Record<string, unknown> = {}): string {
  const template = PLAIN[key];
  if (template === undefined) throw new Error("unknown message key " + key);
  const plain = format(template, params);
  const cheeky = CHEEKY[key];
  if (tone !== "cheeky" || cheeky === undefined) return plain;
  return format(cheeky, { ...params, plain });
}
